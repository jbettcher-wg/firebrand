#!/usr/bin/env python3
"""Generate shared/frb_splash_logo.h: the boot splash logo as palettes + run-length bitmaps.

    tools/mk-splash-logo.py <logo.svg|logo.png> [widths] [grey]
        (defaults: 640,1280 and BFBFBF; run from the top of the repository:
         tools/mk-splash-logo.py art/C-chip.svg)

RadeonNI's tools/mk-splash-logo.py, for more than one size: an SVG is first rendered
with rsvg-convert (3600 px wide); then, for each width, the logo is trimmed, scaled to
that many pixels wide, composited over the splash grey (so the kext needs no alpha
blending), quantised to at most 64 colours, and run-length encoded as (count, palette
index) byte pairs, row-major. Palette index 0 is always the grey itself, so the 8 bpp
splash can fill the screen with index 0. Needs ImageMagick (`magick`) and, for an SVG,
librsvg (`rsvg-convert`).
"""
import os, subprocess, sys, tempfile

src = sys.argv[1]
widths = [int(w) for w in sys.argv[2].split(",")] if len(sys.argv) > 2 else [640, 1280]
grey = (sys.argv[3] if len(sys.argv) > 3 else "BFBFBF").upper()
grey_rgb = int(grey, 16)

tmp = None
if src.lower().endswith(".svg"):
    tmp = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
    tmp.close()
    subprocess.check_call(["rsvg-convert", "-w", "3600", src, "-o", tmp.name])
    raster = tmp.name
else:
    raster = src


def encode(width):
    base = ["magick", raster, "-trim", "+repage", "-resize", f"{width}x", "-background", f"#{grey}",
            "-flatten", "-dither", "None", "-colors", "64", "+repage"]
    w, h = map(int, subprocess.check_output(base + ["-format", "%w %h", "info:"]).split())
    rgb = subprocess.check_output(base + ["-depth", "8", "rgb:-"])
    assert len(rgb) == w * h * 3, (len(rgb), w, h)
    palette, index, pixels = [grey_rgb], {grey_rgb: 0}, []
    for i in range(0, len(rgb), 3):
        c = (rgb[i] << 16) | (rgb[i + 1] << 8) | rgb[i + 2]
        if c not in index:
            index[c] = len(palette)
            palette.append(c)
        pixels.append(index[c])
    assert len(palette) <= 256
    rle, i = [], 0
    while i < len(pixels):
        j = i
        while j < len(pixels) and pixels[j] == pixels[i] and j - i < 255:
            j += 1
        rle += [j - i, pixels[i]]
        i = j
    return w, h, palette, rle


name = os.path.basename(src)
out = [f"/* Generated by tools/mk-splash-logo.py from {name} -- do not edit. */",
       "#ifndef FRB_SPLASH_LOGO_H", "#define FRB_SPLASH_LOGO_H", "",
       f"#define FRB_SPLASH_GREY 0x{grey}u", ""]
table = []
for width in widths:
    w, h, palette, rle = encode(width)
    out += [f"/* {w}x{h}, {len(palette)} colours (index 0 the grey), {len(rle)} RLE bytes */",
            f"static const uint32_t frb_splash_palette_{width}[{len(palette)}] = {{"]
    for k in range(0, len(palette), 8):
        out.append("\t" + ", ".join(f"0x{c:06x}" for c in palette[k:k + 8]) + ",")
    out += ["};", f"static const uint8_t frb_splash_rle_{width}[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        out.append("\t" + ",".join(str(v) for v in rle[k:k + 24]) + ",")
    out += ["};", ""]
    table.append(f"\t{{ {w}, {h}, {len(palette)}, frb_splash_palette_{width}, frb_splash_rle_{width}, "
                 f"sizeof(frb_splash_rle_{width}) }},")
    print(f"shared/frb_splash_logo.h: {w}x{h}, {len(palette)} colours, {len(rle)} RLE bytes")
out += ["/* smallest first; (count, palette index) pairs, row-major, runs never wider than 255 */",
        "static const struct frb_splash_logo frb_splash_logos[] = {"] + table + ["};", "", "#endif", ""]
open("shared/frb_splash_logo.h", "w").write("\n".join(out))
if tmp:
    os.unlink(tmp.name)
